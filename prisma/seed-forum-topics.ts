async function main() {
  /* Учётная запись площадки заводится один раз и переиспользуется: две
     редакции в списке участников выглядели бы странно. */
  const editor = await prisma.user.upsert({
    where: { email: EDITOR.email },
    update: {},
    create: {
      email: EDITOR.email,
      name: EDITOR.name,
      forumSignature: EDITOR.signature,
      /* Пароль случайный и никому не выдаётся: под этой записью не
         входят, от неё только публикуют. */
      hashedPassword: `SEED_${randomUUID()}`,
      role: "USER",
    },
    select: { id: true },
  })

  let created = 0
  let skipped = 0

  for (const item of TOPICS) {
    const section = await prisma.forumSection.findUnique({
      where: { slug: item.section },
      select: { id: true, topicCount: true },
    })
    if (!section) {
      console.log(`раздел не найден: ${item.section}`)
      skipped += 1
      continue
    }

    /* В разделе уже говорят — справка там не нужна: она вытеснит живое
       обсуждение наверх и создаст ощущение казённой площадки. */
    if (section.topicCount > 0) {
      skipped += 1
      continue
    }

    const slug = `${item.section}-spravka-${randomUUID().slice(0, 6)}`
    const now = new Date()

    await prisma.$transaction(async (tx) => {
      await tx.forumTopic.create({
        data: {
          slug,
          title: item.title,
          sectionId: section.id,
          authorId: editor.id,
          prefix: item.prefix ?? null,
          lastPostAt: now,
          /* Справка закрепляется: она отвечает на частый вопрос, и место
             ей наверху, а не в хвосте после живых обсуждений. */
          isPinned: true,
          posts: { create: { authorId: editor.id, content: item.content } },
          subscriptions: { create: { userId: editor.id } },
        },
      })

      await tx.forumSection.update({
        where: { id: section.id },
        data: { topicCount: { increment: 1 }, postCount: { increment: 1 }, lastPostAt: now },
      })

      await tx.user.update({
        where: { id: editor.id },
        data: { forumPostCount: { increment: 1 } },
      })
    })

    created += 1
    console.log(`создано: ${item.title.slice(0, 50)}`)
  }

  console.log(`\nсоздано тем: ${created}, пропущено: ${skipped}`)
}

main()
  .catch((error) => {
    console.error(error)
    process.exit(1)
  })
  .finally(() => prisma.$disconnect())
