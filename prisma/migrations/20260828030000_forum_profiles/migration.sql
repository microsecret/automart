-- Профили участников форума.
--
-- Ответ «у меня так же было» значит разное от владельца той же машины и
-- от постороннего. Профиль показывает, кто отвечает: сколько написал,
-- сколько раз помог, чем ездит.

-- Счётчик сообщений хранится полем, как и остальные счётчики форума:
-- число стоит рядом с каждым сообщением в теме, и COUNT по всем
-- сообщениям автора на каждое из двадцати сообщений страницы — это
-- двадцать запросов там, где нужно ноль.
ALTER TABLE "User" ADD COLUMN "forumPostCount" INTEGER NOT NULL DEFAULT 0;

-- Подпись под сообщениями: обычный текст без разметки и ссылок. Подпись
-- видна под каждым сообщением, и ссылка в ней это реклама на всю
-- площадку.
ALTER TABLE "User" ADD COLUMN "forumSignature" TEXT;

-- Существующие сообщения уже написаны: без переноса у всех авторов был бы
-- ноль при непустом форуме.
UPDATE "User"
SET "forumPostCount" = (
  SELECT COUNT(*) FROM "ForumPost"
  WHERE "ForumPost"."authorId" = "User"."id" AND "ForumPost"."deletedAt" IS NULL
);
