-- Метки тем.
--
-- Метка организует раздел лучше, чем деление на подразделы: в одном
-- списке видно, где просят помощи, где уже нашли решение, а где продают.
-- По ней же фильтруют — человек с поломкой ищет «Помогите», а не читает
-- подряд.
--
-- Существующие темы остаются без метки: проставлять её задним числом
-- значит гадать за автора, о чём была тема.
ALTER TABLE "ForumTopic" ADD COLUMN "prefix" TEXT;

-- Фильтр по метке внутри раздела: без указателя он читает все темы
-- раздела при каждом заходе.
CREATE INDEX "ForumTopic_sectionId_prefix_idx" ON "ForumTopic"("sectionId", "prefix");
