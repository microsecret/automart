-- Код партнёра отдельным полем.
--
-- Код выводится из идентификатора хешем и обратно не разворачивается,
-- поэтому владельца кода искали перебором пользователей с ограничением
-- в две тысячи записей. Партнёр, за которым зарегистрировались две
-- тысячи новых людей, переставал находиться: приглашение отклонялось
-- как «не найдено», а вознаграждение не начислялось — молча, никто из
-- двоих об этом не узнавал.
--
-- Поле заполняется при первом обращении к кабинету партнёра и при
-- разборе приглашения, поэтому здесь только колонка с уникальным
-- индексом: пересчитывать хеши для всей базы в миграции не нужно.
ALTER TABLE "User" ADD COLUMN "referralCode" TEXT;

CREATE UNIQUE INDEX "User_referralCode_key" ON "User"("referralCode");
