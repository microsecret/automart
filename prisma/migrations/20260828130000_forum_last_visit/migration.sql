--
-- По ней подсвечиваются темы, где писали с тех пор: «что нового» —
-- главный сценарий возврата постоянного читателя, и без отметки он каждый
-- раз перечитывает список глазами, вспоминая, что уже видел.
--
-- Одна отметка на человека, а не запись по каждой теме: полная
-- прочитанность потребовала бы строки на каждый заход в каждую тему, то
-- есть тысяч записей ради подсветки, которую видно и так.
--
-- Существующие остаются с пустым значением: для них первый заход после
-- этой правки и станет точкой отсчёта. Проставить «сейчас» задним числом
-- значило бы скрыть от них всё, что накопилось.
