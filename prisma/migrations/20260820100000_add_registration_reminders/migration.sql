-- Учёт напоминаний о незавершённой регистрации.
--
-- Люди подтверждают телефон одним нажатием, а почту и пароль набирают
-- руками — и часть теряется на этом. Бот зовёт их вернуться, а эти поля
-- не дают писать одному и тому же человеку бесконечно.
--
-- Оба поля добавляются с безопасными значениями: существующие строки
-- получают NULL и 0, то есть первое напоминание им отправится штатно.
ALTER TABLE "User" ADD COLUMN "regReminderAt" DATETIME;
ALTER TABLE "User" ADD COLUMN "regReminderCount" INTEGER NOT NULL DEFAULT 0;
