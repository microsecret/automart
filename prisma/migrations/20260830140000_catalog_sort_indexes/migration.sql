-- Индексы под сортировки каталога и дедупликацию просмотров.
--
-- Каталог отдаётся с фильтром «активное и не удалённое» и сортировкой по
-- дате или цене, а в конце всегда идёт разбивка по id. Существующие
-- индексы покрывали это наполовину: по цене индекс есть, но без учёта
-- статуса, поэтому база отбирала строки по одному условию, а сортировала
-- уже в памяти. На первой тысяче объявлений это незаметно; на десятках
-- тысяч страница каталога становится самым медленным местом сайта.
--
-- Порядок полей повторяет порядок в запросе: сначала то, по чему
-- фильтруем, потом то, по чему сортируем.

CREATE INDEX IF NOT EXISTS "Listing_status_deletedAt_price_id_idx"
  ON "Listing"("status", "deletedAt", "price", "id");

CREATE INDEX IF NOT EXISTS "Listing_status_deletedAt_createdAt_id_idx"
  ON "Listing"("status", "deletedAt", "createdAt", "id");

-- Счётчик просмотров ищет, не смотрел ли этот же человек объявление за
-- последний час. Проверка идёт по паре «объявление и отпечаток адреса»,
-- а индексы были порознь: по объявлению и по отпечатку. База выбирала
-- один из них и перебирала остальное — тем дольше, чем популярнее
-- объявление.
CREATE INDEX IF NOT EXISTS "ListingViewEvent_listingId_ipHash_createdAt_idx"
  ON "ListingViewEvent"("listingId", "ipHash", "createdAt");
