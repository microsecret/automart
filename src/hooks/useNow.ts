"use client"

import { useEffect, useState } from "react"

/**
 * «Сейчас» — только в браузере, после первой отрисовки.
 *
 * Главная отдаётся из кэша (ISR, stale-while-revalidate): первый посетитель
 * после паузы получает HTML, отрисованный минуты или часы назад. Всё, что
 * считается от текущего момента — метка «Сегодня», «3 часа назад», —
 * на сервере и в браузере выходило разным, и React падал с #418 и
 * перерисовывал страницу целиком. Поймано 27.09.2026: объявление пересекло
 * границу суток между сборкой и заходом.
 *
 * До монтирования хук возвращает null — и сервер, и первая отрисовка в
 * браузере показывают одно и то же (ничего), а время подставляется сразу
 * после гидратации.
 */
export function useNow(): number | null {
  const [now, setNow] = useState<number | null>(null)
  useEffect(() => {
    setNow(Date.now())
  }, [])
  return now
}
