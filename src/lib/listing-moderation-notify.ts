/**
 * Уведомление продавца о решении модератора.
 *
 * Одобрение и отклонение объявления не сообщались продавцу вовсе:
 * инфраструктура уведомлений используется в пятнадцати местах проекта, а
 * в модерации — самом важном для продавца событии — её не было. Человек
 * отправлял объявление и узнавал судьбу только случайным заходом в
 * кабинет: одобренное не начинал продвигать, отклонённое не исправлял.
 *
 * Тексты отделены от отправки: их нужно проверять без базы и Telegram.
 */

/* Статусы продублированы строками, а не импортированы из
   listing-lifecycle: модуль проверяется тестовым раннером node, который
   не знает алиас @/, и ради двух констант тянуть зависимость незачем. */
const STATUS = { ACTIVE: "ACTIVE", REJECTED: "REJECTED", ARCHIVED: "ARCHIVED", PAUSED: "PAUSED" } as const

export type ModerationNotice = {
  title: string
  content: string
  type: "SUCCESS" | "WARNING" | "INFO"
}

/**
 * Текст уведомления по решению модератора; null — событие не для продавца.
 *
 * Уведомляются только решения, меняющие судьбу объявления: одобрение,
 * отклонение, снятие с публикации. Технические переходы (черновик,
 * ожидание модерации) продавец инициирует сам, и сообщать о них — шум.
 */
export function moderationNotice(
  toStatus: string,
  listingTitle: string,
  reason?: string | null,
): ModerationNotice | null {
  const name = listingTitle.trim() || "Объявление"

  if (toStatus === STATUS.ACTIVE) {
    return {
      title: "Объявление опубликовано",
      /* Момент одобрения — самая сильная точка предложения продвижения:
         продавец только что узнал, что объявление видно покупателям, и
         хочет продать быстрее. */
      content:
        `«${name}» прошло проверку и видно покупателям. ` +
        "Хотите продать быстрее — поднимите объявление в топ в кабинете, раздел «Продвижение».",
      type: "SUCCESS",
    }
  }

  if (toStatus === STATUS.REJECTED) {
    return {
      title: "Объявление не прошло проверку",
      /* Причина обязательна при отклонении (маршрут это требует), но
         текст не должен падать, если её всё же нет. */
      content:
        `«${name}» отклонено модератором.` +
        (reason ? ` Причина: ${reason}.` : "") +
        " Исправьте замечание и отправьте объявление снова — это бесплатно.",
      type: "WARNING",
    }
  }

  if (toStatus === STATUS.ARCHIVED || toStatus === STATUS.PAUSED) {
    return {
      title: "Объявление снято с публикации",
      content:
        `«${name}» скрыто модератором.` +
        (reason ? ` Причина: ${reason}.` : "") +
        " Если считаете это ошибкой, напишите в поддержку.",
      type: "INFO",
    }
  }

  return null
}
