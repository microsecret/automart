/**
 * Куда ведёт уведомление.
 *
 * Уведомления были тупиком: «по вашей заявке пришло предложение», «ваше
 * объявление одобрено», «начислено вознаграждение» — и никакого способа
 * перейти к тому, о чём речь. Человек читал новость и шёл искать её
 * руками через меню, хотя связь с предметом лежала в самой записи:
 * `relatedType` и `relatedId` заполнялись двенадцатью разными местами и
 * не читались нигде.
 *
 * Ведём туда, где предмет виден наверняка. Адреса объявления и темы
 * форума из одного идентификатора не собираются — там нужен ещё тип
 * объявления или slug раздела, — поэтому такие уведомления ведут в
 * список, а не в подложную ссылку, которая откроет «страница не
 * найдена».
 *
 * Уведомление без известного адресата остаётся просто текстом: часть из
 * них ничего не открывает и по смыслу — сообщение администратора,
 * истечение продвижения в чате.
 */
export function notificationHref(
  relatedType: string | null | undefined,
  _relatedId?: string | null,
): string | null {
  if (!relatedType) return null

  switch (relatedType) {
    /* Заявка «ищу деталь»: ответы магазинов лежат на своей странице —
       отдельного адреса у самой заявки нет. */
    case "PART_REQUEST":
      return "/dashboard/part-requests"

    case "PART_ORDER":
      return "/dashboard/orders"

    case "DELIVERY_ORDER":
      return "/dashboard/deliveries"

    /* Объявление живёт по адресу вида /listings/vehicle/{id}: типа в
       уведомлении нет, и угадывать его нельзя — ведём в список своих. */
    case "LISTING":
    case "LISTING_REPORT":
      return "/dashboard"

    case "FORUM_TOPIC":
      return "/forum/subscriptions"

    /* Заявка на аукционе партнёру видна только в админке: своей
       страницы у неё пока нет, и вести человека некуда. */
    case "AUCTION_INQUIRY_OFFER":
      return null

    /* Все три награды партнёра ведут в один кабинет: начисление, выплата
       и привлечение разделены только в тексте, а счёт человек смотрит
       общий. */
    case "REFERRAL_ATTRIBUTION":
    case "REFERRAL_PAYOUT":
    case "REFERRAL_REWARD":
      return "/dashboard/referral"

    default:
      return null
  }
}
