/**
 * Русское склонение по числу: «1 заправка», «2 заправки», «5 заправок».
 *
 * Отдельный модуль без зависимостей, а не строка в общем `format`: тот
 * тянет за собой разбор картинок и числовые форматы через псевдоним
 * `@/`, который тест-раннер не резолвит, а склонение нужно и в
 * серверных рассылках, и в тестах.
 *
 * Это уже третье место, где понадобилась та же функция: в `format` она
 * есть для интерфейса, в витрине заправок чуть не завелась копия, и в
 * сводке для чатов — тоже. Копии расходятся при первой правке.
 */
export function plural(count: number, one: string, few: string, many: string): string {
  const mod10 = count % 10
  const mod100 = count % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few
  return many
}
