/**
 * Данные для поисковиков внутри <script type="application/ld+json">.
 *
 * JSON.stringify не экранирует «<»: заголовок темы форума или название
 * сети АЗС с «</script>» закрывало блок, и остальное выполнялось на
 * странице как разметка. На форуме стояла замена на "<" — но в
 * строке JS это и есть сам символ «<», замена ничего не меняла (аудит
 * 28.10.2026). Нужна запись из шести знаков: обратная косая, u, 003c.
 *
 * U+2028 и U+2029 — разделители строк, которые старые движки JS не
 * принимают внутри строковых литералов.
 */
export function serializeJsonLd(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029")
}
