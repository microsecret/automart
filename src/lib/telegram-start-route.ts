/**
 * Куда вести человека, пришедшего в мини-приложение по кнопке.
 *
 * Кнопки передают цель через startapp: «разместить объявление» — create,
 * подписка на заправку — fuelsub_<источник>_<идентификатор>. Без разбора
 * все попадали на главную приложения: человек жал «разместить», а
 * оказывался не там.
 *
 * Живёт отдельно от компонента, а не рядом с ним: там модуль клиентский и
 * тянет Telegram WebApp, и проверить чистую функцию тестами было бы
 * нельзя. А ошибка здесь молча уводит людей не туда — её надо ловить.
 */

/* Модуль без импортов — намеренно.

   Разбор параметра надо проверять тестами: ошибка здесь молча уводит
   людей на несуществующую страницу. А запускатель тестов не разбирает ни
   псевдоним «@/», ни расширение «.ts» в путях, которое требует настройки
   компилятора. Адрес размещения объявления совпадает с реестром
   навигации, и тест это сторожит. */
export const CREATE_VEHICLE_ROUTE = "/listings/create/vehicle"

/* Куда вести, если человек пришёл по кнопке из бота.

   Кнопки передают цель через startapp: «разместить объявление» — create.
   Без разбора все попадали на главную приложения, то есть жали
   «разместить», а оказывались не там.

   Только известные значения: чужой параметр стал бы открытым
   перенаправлением внутри приложения. */
const START_PARAM_ROUTES: Record<string, string> = {
  create: `${CREATE_VEHICLE_ROUTE}?source=telegram`,
  promo: "/auctions?from=telegram",
  /* Вход ради топлива.

     Приглашение на карте АЗС давно звало сюда ссылкой `?startapp=fuel`,
     но значение в этом списке не значилось: `resolveStartRoute` возвращал
     null, и человек, вошедший ради цен на бензин, попадал на ленту машин.
     Он приходил за одним, получал другое — и уходил. */
  fuel: "/services/fuel-map?from=telegram",
}

/* Объявление из поста в чате: listing_<идентификатор>.

   Идентификатор проверяется по набору символов, а не подставляется как
   есть: без проверки чужая строка в параметре увела бы человека на
   произвольный адрес внутри приложения. */
const LISTING_PARAM = /^listing_([0-9a-f-]{16,40})$/i

/* Подписка на заправку из чата: fuelsub_<источник>_<идентификатор>.

   Человек нажимает в городском чате «сообщать мне о таком», а войти ещё
   не успел. Без этого он после входа попадал на общую карту города и
   терял и заправку, и марку, и само намерение — то есть проделывал путь
   до входа ради того, чтобы начать заново.

   Идентификаторы заправок выглядят как «gdebenz-1119699898» или
   «gdebenz-usr_soJeHhLAT04»: дефис в startapp Telegram не пропускает, и
   в параметре он заменён подчёркиванием. Набор символов проверяется —
   иначе чужая строка увела бы человека на произвольный адрес. */
const FUEL_SUB_PARAM = /^fuelsub_([a-z0-9]{1,20})_([a-z0-9_]{1,60})$/i

/* Тема форума: forum_<раздел>__<тема>.

   Раздел и тема вместе, потому что адрес темы содержит раздел и без него
   страница отвечает «не найдено». Разделитель двойной: в самих адресах
   встречаются дефисы, но не подчёркивания, и одинарное могло бы попасться
   внутри. Набор символов проверяется — иначе чужая строка в параметре
   увела бы человека на произвольный адрес внутри приложения. */
const FORUM_PARAM = /^forum_([a-z0-9-]{1,80})__([a-z0-9-]{1,120})$/i

export function resolveStartRoute(initData: string, search = ""): string | null {
  try {
    const startParam = (
      new URLSearchParams(initData).get("start_param")
      || new URLSearchParams(search).get("start")
    )?.trim()
    if (!startParam) return null

    const known = START_PARAM_ROUTES[startParam]
    if (known) return known

    const listing = startParam.match(LISTING_PARAM)
    if (listing) return `/listings/vehicle/${listing[1]}?from=telegram`

    const fuelSub = startParam.match(FUEL_SUB_PARAM)
    if (fuelSub) {
      /* Подчёркивания возвращаются дефисами: «gdebenz_1119699898» — это
         заправка «gdebenz-1119699898». Хвост «usr_...» встречается у
         части источников, поэтому восстанавливается только первый
         разделитель, отделяющий источник от идентификатора. */
      const stationId = `${fuelSub[1]}-${fuelSub[2]}`
      return `/services/fuel-map?station=${encodeURIComponent(stationId)}&subscribe=1&from=telegram`
    }

    const forum = startParam.match(FORUM_PARAM)
    if (forum) return `/forum/${forum[1]}/${forum[2]}?from=telegram`

    return null
  } catch {
    return null
  }
}
