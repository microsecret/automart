/**
 * Склонение названий городов и регионов.
 *
 * Вынесено из fuel-city-slug отдельным модулем по двум причинам. Правило
 * не связано с заправками: те же заголовки нужны страницам объявлений и
 * запчастей по городам. И у него нет зависимостей, поэтому его можно
 * проверять тестом напрямую — модуль заправок тянет справочник координат
 * через псевдоним «@/lib», который понимает сборщик, но не тестовый
 * запуск Node, и функция оставалась непроверенной.
 */

/**
 * Город в предложном падеже: «в Уфе», а не «в Уфа».
 *
 * Заголовок страницы читает человек, и «Цены на бензин в Уфа» выдаёт
 * машинную сборку текста — доверия такой странице меньше, а поисковик
 * сверяет заголовок с живым запросом «цены на бензин в уфе».
 *
 * Правило простое и покрывает подавляющее большинство русских городов.
 * Несклоняемые названия и составные вроде «Набережные Челны» остаются как
 * есть: лучше не склонять вовсе, чем склонить неверно.
 */
const INDECLINABLE = /(ово|ево|ино|ыно|аул|бург|ск|цк|дск|рск)$/i

export function cityInPrepositional(city: string): string {
  const trimmed = city.trim()
  if (!trimmed) return trimmed

  /* Области и края склоняются отдельно.

     Общее правило ниже пропускает всё, где есть пробел, — и заголовок
     выходил «Цены на бензин в Московская область». Областей в списке
     сбора уже четыре, включая Московскую и Свердловскую, и каждая давала
     такую строку на своей странице.

     Прилагательное на -ая переходит в -ой, само слово «область» — в
     «области»: «в Московской области». Край и республика устроены так
     же. */
  const compound = trimmed.match(/^(.+?)(ая)\s+(область|республика)$/i)
  if (compound) {
    const [, stem, , kind] = compound
    const kindPrepositional = kind.toLowerCase() === "область" ? "области" : "республике"
    return `${stem}ой ${kindPrepositional}`
  }

  const kray = trimmed.match(/^(.+?)(ий|ый)\s+край$/i)
  if (kray) return `${kray[1]}ом крае`

  /* Республики с названием в родительном падеже — «Республика
     Башкортостан» — меняют только первое слово. */
  const republic = trimmed.match(/^Республика\s+(.+)$/i)
  if (republic) return `Республике ${republic[1]}`

  if (trimmed.includes(" ") || trimmed.includes("-")) return trimmed

  /* Города на -ск, -бург и подобные в предложном падеже не меняют основу:
     «в Челябинске» — это уже добавленное окончание, а не замена. */
  if (INDECLINABLE.test(trimmed)) {
    return /(ово|ево|ино|ыно)$/i.test(trimmed) ? trimmed : `${trimmed}е`
  }

  /* Названия на -ия и -ья: «Мордовия» → «Мордовии», «Марий Эл» сюда не
     попадает, у него пробел. Правило стояло во второй копии функции и
     при слиянии могло потеряться. */
  if (/(ия|ья)$/i.test(trimmed)) return `${trimmed.slice(0, -1)}и`

  const last = trimmed.slice(-1).toLowerCase()
  /* Женский род на -а и -я: Уфа → Уфе, Казань уже мягкая и идёт ниже. */
  if (last === "а") return `${trimmed.slice(0, -1)}е`
  if (last === "я") return `${trimmed.slice(0, -1)}е`
  /* Мягкий знак: Казань → Казани, Тверь → Твери. */
  if (last === "ь") return `${trimmed.slice(0, -1)}и`
  /* Мужской род на согласную: Салават → Салавате. */
  if (/[бвгджзйклмнпрстфхцчшщ]/i.test(last)) return `${trimmed}е`

  return trimmed
}
