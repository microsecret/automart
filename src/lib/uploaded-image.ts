/**
 * Загруженные картинки показываются без оптимизатора Next.
 *
 * Next составляет список файлов папки public при сборке, и всё, что
 * загружено после неё, для него не существует: оптимизатор отвечает «не
 * является изображением», а карточка показывает «Без фото». Проверено на
 * продакшене — файл от 11 августа отдавался, файлы от 28-го нет, хотя
 * лежали в той же папке и nginx их отдавал.
 *
 * Оптимизировать их и не нужно: загрузка уже уменьшает картинку до 1920
 * и жмёт с качеством 82. Вторая обработка отняла бы время и место ради
 * файла, который и так готов к показу.
 */

/** Загружена ли картинка людьми — в отличие от встроенных в сборку. */
export function isUploadedImage(src: string | null | undefined): boolean {
  return typeof src === "string" && src.startsWith("/uploads/")
}
