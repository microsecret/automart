/**
 * Загруженные людьми картинки проходят через оптимизатор Next.
 *
 * Раньше они показывались в обход него. Причина была настоящей: Next
 * составлял список файлов папки public при сборке, и всё, что загружено
 * после неё, для него не существовало — оптимизатор отвечал «не является
 * изображением», а карточка показывала «Без фото».
 *
 * Сейчас это не воспроизводится. Проверка на боевом сервере: тот же файл
 * через `/_next/image?w=384` отдаётся за 16.6 КБ вместо 338 КБ оригинала,
 * и так же ведут себя свежезагруженные снимки. Разница двадцатикратная —
 * каталог на телефоне весил 3 МБ, из них 3050 КБ картинок, и почти всё это
 * фотографии, отданные в полном размере в слот шириной около 200 пикселей.
 *
 * Флаг оставлен для внешних адресов: у лотов с зарубежных площадок фото
 * лежат на чужих CDN, их обрабатывать не нужно и нельзя.
 */

/** Загружена ли картинка людьми — в отличие от встроенных в сборку. */
export function isUploadedImage(src: string | null | undefined): boolean {
  return typeof src === "string" && src.startsWith("/uploads/")
}

/**
 * Показывать ли картинку в обход оптимизатора.
 *
 * Обход нужен только внешним адресам. Для своих файлов, включая
 * `/uploads`, оптимизатор подбирает ширину под слот и формат под браузер.
 */
export function shouldBypassOptimizer(src: string | null | undefined): boolean {
  return typeof src === "string" && !src.startsWith("/")
}
