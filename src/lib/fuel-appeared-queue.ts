/**
 * Очередь сообщений о появлении топлива.
 *
 * Прогон сбора приносит появления пачкой: за один проход по Уфе
 * источник отдал четыре новости разом, и все четыре ушли в чат в одну
 * секунду. Порог по чату их не удержал — каждая проверяла базу раньше,
 * чем предыдущая успевала записаться.
 *
 * Простое ожидание порога чинит одновременность, но ценой потери:
 * вторая, третья и четвёртая новости просто выбрасывались. Владелец
 * просил обратного — чтобы чат поднимался наверх и люди видели, что
 * система работает. Поэтому появления не отбрасываются, а становятся в
 * очередь и уходят по одному с паузой.
 *
 * Здесь только выбор момента и порядка, без сети и базы: то, что решает
 * судьбу сообщений в чате на две тысячи человек, должно проверяться
 * тестами.
 */

/* Пауза между сообщениями в один чат.
 *
 * Telegram разрешает группе двадцать сообщений в минуту; минута между
 * постами не приближается к границе даже близко и при этом не даёт чату
 * превратиться в ленту, пролистываемую не глядя. */
export const QUEUE_INTERVAL_MS = 60_000

/* Сколько появлений держим в очереди.
 *
 * Прогон по всей России способен принести сотни новостей разом. Слать их
 * сутки подряд по одной в минуту бессмысленно: к вечеру топливо давно
 * разберут, а чат утонет в устаревшем. Двадцать сообщений — это двадцать
 * минут живой ленты, дальше очередь обновится следующим прогоном. */
export const QUEUE_LIMIT = 20

export type QueuedAppearance<T> = {
  /** Ключ заправки: повтор той же точки в очереди не нужен. */
  key: string
  payload: T
}

/**
 * Складывает новые появления в очередь.
 *
 * Повторы по той же заправке отбрасываются: пока сообщение ждёт
 * отправки, второй источник успевает сказать про ту же колонку то же
 * самое. Переполнение режет хвост, а не голову — первые новости прогона
 * свежее тех, что пришли последними, только если очередь уже длинная.
 */
export function enqueueAppearances<T>(
  queue: QueuedAppearance<T>[],
  incoming: QueuedAppearance<T>[],
): QueuedAppearance<T>[] {
  const seen = new Set(queue.map((item) => item.key))
  const next = [...queue]

  for (const item of incoming) {
    if (seen.has(item.key)) continue
    seen.add(item.key)
    next.push(item)
  }

  return next.slice(0, QUEUE_LIMIT)
}

/**
 * Сколько ждать до следующей отправки.
 *
 * Ноль означает «можно прямо сейчас»: либо в чат ещё не писали, либо
 * пауза уже вышла. Отрицательных значений не возвращает — часы сервера
 * и записи в базе иногда расходятся, и ожидание в минус подвесило бы
 * отправку навсегда.
 */
export function delayUntilNextPost(lastPostAt: Date | null, now: Date, intervalMs = QUEUE_INTERVAL_MS): number {
  if (!lastPostAt) return 0
  const elapsed = now.getTime() - lastPostAt.getTime()
  if (elapsed >= intervalMs) return 0

  /* Запись из будущего — часы сервера ушли вперёд или база отдала время
     другой зоны. Отрицательный `elapsed` растянул бы ожидание на десять
     минут вместо одной, и чат замолчал бы без единой ошибки в логах.
     Больше интервала ждать не за чем никогда. */
  return Math.min(intervalMs, Math.max(0, intervalMs - elapsed))
}
