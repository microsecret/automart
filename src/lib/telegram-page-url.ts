/**
 * Адрес страницы сайта, открываемой как мини-приложение.
 *
 * Кнопки под уведомлениями обещали конкретное — «Открыть заказы»,
 * «Ответить», — а вели на главный экран мини-приложения: человек
 * попадал в ленту машин и дальше искал сам то, о чём его только что
 * известили. Мини-приложение это тот же сайт, поэтому нужную страницу
 * можно открыть прямо, пометив её как переход из Telegram — иначе к ней
 * приедут десктопная шапка с подвалом.
 *
 * Возвращает null там же, где нет адреса мини-приложения: без него
 * кнопку показывать нельзя.
 */
export function buildTelegramPageUrl(base: string | null, path: string) {
  if (!base) return null

  try {
    const url = new URL(path, base)
    /* Только свой сайт: чужой адрес Telegram в мини-приложении всё
       равно не откроет, а подставить его туда не должно быть
       возможности. */
    if (url.origin !== new URL(base).origin) return null
    url.searchParams.set("from", "telegram")
    return url.toString()
  } catch {
    return null
  }
}
