/**
 * Отсев неправдоподобных цен, приходящих от источников АЗС.
 *
 * Замер на боевой базе 16 сентября 2026: из 21 615 цен АИ-95 около
 * 22 процентов выходили за любые разумные пределы — вплоть до 195 ₽ за
 * литр в Тюмени и 139 ₽ в Казани. Это не региональная дороговизна: те же
 * выбросы сидят в Рязани, Самаре и Нижнем Новгороде, где бензин стоит
 * как везде.
 *
 * Разбор станции целиком показал природу ошибки. У точки «Иликом» в
 * Казани источник отдаёт АИ-100 за 110 ₽, а АИ-92 за 129 ₽ — то есть
 * девяносто второй дороже сотого. Так не бывает нигде: октановое число
 * и цена растут вместе. Значит, испорчена не одна графа, а вся запись,
 * и доверять её ценам нельзя ни по одной марке.
 *
 * Отсюда две проверки. Первая — потолок и пол по марке: цена вне
 * коридора отбрасывается поштучно. Вторая — порядок марок внутри
 * станции: если дешёвое топливо дороже дорогого, отбрасывается вся
 * станция.
 *
 * Почему это важно за пределами витрины: карта показывает эти же цены
 * человеку как настоящие. Водитель, увидевший 195 ₽ за АИ-95, решает,
 * что сломана площадка, — и он прав.
 */

/** Коридор правдоподобия по марке: копейки за литр. */
type PriceRange = { min: number; max: number }

/*
 * Границы взяты по распределению боевой базы с запасом в обе стороны.
 *
 * Нижние проценты трезвые и их трогать нельзя: АИ-92 от 60 ₽, газ от
 * 28 ₽ — это реальные цены, а не ошибки. Поэтому пол опущен заметно
 * ниже первого процентиля: отсекать надо мусор, а не дешёвые регионы.
 *
 * Потолок стоит выше медианы примерно вдвое. Он ловит явную порчу
 * (139 ₽ за АИ-92) и при этом оставляет место дорогим районам вроде
 * Чукотки и Камчатки, где топливо действительно дороже материкового.
 */
const PRICE_RANGES: Record<string, PriceRange> = {
  AI92: { min: 3_000, max: 11_000 },
  AI95: { min: 3_200, max: 12_000 },
  AI98: { min: 3_500, max: 16_000 },
  AI100: { min: 4_000, max: 18_000 },
  DT: { min: 3_000, max: 13_000 },
  GAS: { min: 1_200, max: 6_000 },
}

/*
 * Порядок марок по октановому числу: дешёвое слева.
 *
 * Дизель в этот ряд не входит — он живёт по своей экономике и в разные
 * сезоны бывает и дешевле девяносто второго, и дороже девяносто пятого.
 * Газ тем более: он втрое дешевле бензина и сравнивать его не с чем.
 *
 * АИ-98 исключён, и это стоило пробного прогона чистки. Первая версия
 * держала его в ряду — и скрипт снёс честные цены Башнефти в Ижевске
 * (92 за 66,70 · 95 за 68,30 · 98 за 65,70) вместе с Татнефтью в
 * Казани, у которой всё было в порядке.
 *
 * Замер по базе объяснил почему: у 328 станций девяносто восьмой
 * дешевле девяносто пятого при совершенно разумных ценах обеих марок.
 * Это не порча, а рынок: 98-й продают по акции, а «премиальный» 95-й с
 * присадками стоит дороже простого 98-го. Для сравнения, настоящий
 * переворот — 92-й дороже 100-го — встречается всего на 95 станциях.
 *
 * Правило должно ловить редкое и явное, а не частое и объяснимое.
 */
const OCTANE_ORDER = ["AI92", "AI95", "AI100"]

export type SanityCheckedPrice = {
  fuel: string
  priceRub: number
}

/** Цена марки лежит в коридоре правдоподобия. */
export function isPlausiblePrice(fuel: string, priceRub: number): boolean {
  const range = PRICE_RANGES[fuel]
  /* Незнакомая марка не повод выбрасывать данные: источник может
     научиться отдавать что-то новое раньше, чем мы опишем коридор. */
  if (!range) return Number.isFinite(priceRub) && priceRub > 0
  if (!Number.isFinite(priceRub)) return false
  return priceRub >= range.min && priceRub <= range.max
}

/**
 * Цены станции согласованы между собой: бензин дорожает с октаном.
 *
 * Проверяются только соседние известные марки. Если у точки есть АИ-92
 * и АИ-100, но нет АИ-95, сравниваются те две, что есть, — пропуск в
 * середине ряда ничего не портит.
 */
export function hasConsistentOctaneOrder(prices: SanityCheckedPrice[]): boolean {
  const known = OCTANE_ORDER
    .map((fuel) => {
      const found = prices.find((price) => price.fuel === fuel)
      return found ? { fuel, priceRub: found.priceRub } : null
    })
    .filter((entry): entry is { fuel: string; priceRub: number } => entry !== null)

  /* Одна марка сама себе не противоречит. */
  if (known.length < 2) return true

  for (let index = 1; index < known.length; index += 1) {
    /* Строгое сравнение было бы слишком придирчивым: у сетей случается
       акция, когда девяносто пятый идёт по цене девяносто второго, и
       равенство цен — это не порча данных. Отбрасываем только явный
       переворот, когда дешёвая марка дороже дорогой. */
    if (known[index - 1].priceRub > known[index].priceRub) return false
  }
  return true
}

/**
 * Оставляет от станции только те цены, которым можно верить.
 *
 * Порядок проверок здесь решает всё, и первая версия ошиблась именно в
 * нём. Порядок марок сверялся уже по отсеянному списку — а у станции
 * «Иликом» коридор снимал три завышенные цены из четырёх, оставлял
 * одинокий АИ-100 за 110 ₽, и проверять порядок становилось не по чему.
 * Порченая запись протаскивала свою цену на карту.
 *
 * Значит, признак порчи надо искать в сыром виде, до отсева: там видно,
 * что АИ-92 дороже АИ-100, чего не бывает.
 *
 * Но отсюда не следует, что всякий переворот убивает станцию. Отличить
 * порчу от единичной опечатки источника позволяет то, сколько марок
 * пережило коридор. Выжило большинство — переворот устроила одна цена,
 * её коридор и снял, остальному верим. Выжили крохи — доверять нечему.
 */
export function sanitizeStationPrices<T extends SanityCheckedPrice>(prices: T[]): T[] {
  const withinRange = prices.filter((price) => isPlausiblePrice(price.fuel, price.priceRub))
  if (!withinRange.length) return []

  /* Сырые данные согласованы — станция честная, отсеивать больше нечего. */
  if (hasConsistentOctaneOrder(prices)) return withinRange

  /* Переворот в сырых ценах. Если коридор снял меньше половины марок,
     порча точечная: у станции с АИ-92 за 129 ₽ при честных АИ-95 и ДТ
     виновата одна графа, и она уже выброшена. */
  const survivedMost = withinRange.length * 2 > prices.length
  if (survivedMost && hasConsistentOctaneOrder(withinRange)) return withinRange

  return []
}
