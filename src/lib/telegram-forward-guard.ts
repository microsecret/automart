/**
 * Пересылки из чужих каналов в чатах площадки.
 *
 * Чат нужен для объявлений о машинах. Пересланный пост из чужого канала —
 * это чужая реклама: человек ничего не написал сам, а место в ленте
 * занял. Отличить такое от обычного сообщения можно точно, потому что
 * Telegram помечает пересылку служебными полями.
 *
 * Разбор вынесен отдельно от обработчика: тот тянет базу и Telegram, и
 * проверить правила без запуска всего приложения было бы нельзя.
 */

/** Что известно о сообщении для решения о пересылке. */
export type ForwardCheckInput = {
  forward_origin?: {
    type?: string
    chat?: { id?: number | string; type?: string }
    sender_chat?: { id?: number | string; type?: string }
  }
  forward_from_chat?: { id?: number | string; type?: string }
  /** Канал, привязанный к самой группе: его посты — не чужая реклама. */
  sender_chat?: { id?: number | string; type?: string }
  /** Telegram сам пересылает посты привязанного канала в обсуждение. */
  is_automatic_forward?: boolean
}

/**
 * Переслан ли пост из чужого канала.
 *
 * Что НЕ считается таким:
 * — пересылка сообщения человека (это цитата в разговоре, не реклама);
 * — автоматическая пересылка поста привязанного канала — её делает сам
 *   Telegram, и удалять её значит ломать обсуждение под постом;
 * — пересылка из группы или чата: рекламу гонят каналами.
 */
export function isChannelForward(message: ForwardCheckInput): boolean {
  /* Пост привязанного канала Telegram пересылает сам — это не действие
     человека, и удалять его нельзя: пропадёт заголовок обсуждения. */
  if (message.is_automatic_forward) return false

  const origin = message.forward_origin
  if (origin) {
    // Новый формат: пересылка канала помечается типом.
    if (origin.type === "channel") return true
    // Отправитель-канал в старых клиентах приходит внутри origin.
    const originChat = origin.chat || origin.sender_chat
    return originChat?.type === "channel"
  }

  // Старый формат: канал-источник отдельным полем.
  return message.forward_from_chat?.type === "channel"
}

/**
 * Текст предупреждения о пересылке.
 *
 * Тон объясняющий, а не запретительный: человек чаще всего не знал
 * правила, а не нарушал нарочно. Поэтому сразу говорим, что делать
 * вместо пересылки, — иначе он просто уйдёт из чата.
 */
export function forwardNoticeText(userMention: string): string {
  return [
    `📌 <b>${userMention}, пересылку из каналов мы убираем</b>`,
    "",
    "В чате продают машины, а не рекламируют каналы — поэтому репосты со стороны удаляются автоматически.",
    "",
    "✍️ <b>Своё объявление — пожалуйста:</b>",
    "• напишите текстом, добавьте фото и цену;",
    "• или разместите в приложении — оно попадёт и на сайт <b>lewheel.ru</b>, где его найдут через поиск.",
    "",
    "🆓 И то и другое бесплатно.",
    "⏳ Это уведомление исчезнет через 5 минут.",
  ].join("\n")
}
