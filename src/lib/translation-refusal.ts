/**
 * Отказ переводчика, выданный за перевод.
 *
 * В поле «Местонахождение» у сорока четырёх лотов на боевом сайте стояло:
 * «Это не автомобильный текст. Пожалуйста, предоставьте текст для перевода.»
 * Это ответ языковой модели, которой скормили короткое название города:
 * она не признала его автомобильным текстом и отказалась работать, а отказ
 * сохранился как результат.
 *
 * Проверка «есть ли кириллица» такой ответ пропускает — он написан
 * по-русски. Нужна проверка по смыслу: модель говорит о самой задаче
 * перевода, а не переводит.
 *
 * Текст попадал не только в карточку, но и в разметку для поисковиков,
 * то есть уходил в выдачу.
 */

/**
 * Признаки того, что модель заговорила о задаче вместо её выполнения.
 *
 * Список ведётся по реальным ответам, а не по догадкам: каждый образец
 * встречался в базе или в логах. Проверка нарочно нестрогая — лучше
 * отбросить сомнительный перевод и показать запасную подпись, чем
 * опубликовать разговор модели с самой собой.
 */
/* `\w` в регулярных выражениях JavaScript — это латиница, цифры и
   подчёркивание; русские буквы в него не входят. Окончания слов задаются
   явным диапазоном [а-яё], иначе «предоставьте» не совпадёт с
   «предостав\w+». На этом первая версия проверки и споткнулась. */

/**
 * Признаки того, что модель заговорила о задаче вместо её выполнения.
 *
 * Список ведётся по реальным ответам, а не по догадкам: каждый образец
 * встречался в базе или в логах. Проверка нарочно нестрогая — лучше
 * отбросить сомнительный перевод и показать запасную подпись, чем
 * опубликовать разговор модели с самой собой.
 */
const REFUSAL_PATTERNS: readonly RegExp[] = [
  // «Это не автомобильный текст», «текст не является автомобильным»
  /не\s+(?:является\s+)?автомобильн[а-яё]*\s+текст/i,
  /это\s+не\s+автомобильн/i,
  // «Пожалуйста, предоставьте текст», «предоставьте текст для перевода»
  /предостав[а-яё]+\s+текст/i,
  // «Не могу перевести», «не удалось перевести», «перевод невозможен»
  /не\s+(?:могу|может|удалось|получается)\s+перевес/i,
  /перевод\s+(?:невозможен|не\s+требуется)/i,
  // «Введите текст», «укажите текст для перевода»
  /(?:введите|укажите)\s+текст/i,
  // «Текст для перевода отсутствует / пуст / не предоставлен»
  /текст\s+для\s+перевода\s+(?:отсутству|пуст|не\s+пред)/i,
  // Модель объясняет, что перед ней: «это корейский текст»
  /это\s+(?:корейск|японск|китайск|английск)[а-яё]*\s+текст/i,
  // Извинения — модель почти всегда начинает отказ с них
  /^(?:извините|прошу\s+прощения|к\s+сожалению)[,.\s]/i,
  // Пояснение вместо перевода: ответ начинается с «Перевод:»
  /^перевод\s*:/i,
]

/**
 * Ответила ли модель отказом вместо перевода.
 *
 * @param translated ответ модели
 */
export function isTranslationRefusal(translated: string | null | undefined): boolean {
  const text = translated?.trim()
  if (!text) return false
  return REFUSAL_PATTERNS.some((pattern) => pattern.test(text))
}

/**
 * Годится ли ответ как перевод короткой подписи — города, цвета, названия.
 *
 * Кроме отказа отсеивается ответ длиннее исходника в разы: короткое
 * «서울» не переводится в два предложения, а если модель выдала абзац —
 * она объясняет, а не переводит.
 */
export function isUsableShortTranslation(source: string, translated: string | null | undefined): boolean {
  const text = translated?.trim()
  if (!text) return false
  if (isTranslationRefusal(text)) return false
  /* Перевод короткой подписи не бывает длиннее исходника втрое.

     Порог взят с запасом: «서울» → «Сеул» это рост в два раза по знакам,
     а «부산광역시» → «Пусан» — сокращение. Втрое длиннее — это уже проза. */
  const limit = Math.max(40, source.trim().length * 3)
  return text.length <= limit
}
