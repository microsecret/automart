/**
 * Название чата по городу объявления.
 *
 * Возвращает общий чат страны, когда город не опознан или не указан:
 * объявление без адреса всё равно надо кому-то показать.
 */
export function pickChatTitleForCity(city: string | null | undefined): string {
  if (typeof city !== "string") return FALLBACK_CHAT_TITLE

  /* Поле города человек заполняет руками: встречается «йошкар ола» с
     малой буквы, «Гафурийский район село красноусольск» и «Альметьевск,
     Казань» через запятую. Поэтому сравниваем по вхождению в приведённой
     строке, а не по равенству.

     Буква «ё» приводится к «е»: половина пишет «Королёв», половина
     «Королев», и держать оба написания в каждом списке — верный способ
     однажды забыть одно из них. */
  const normalized = city.toLowerCase().replace(/ё/g, "е").trim()
  if (!normalized) return FALLBACK_CHAT_TITLE

  for (const area of AREAS) {
    for (const place of area.places) {
      if (normalized.includes(place.replace(/ё/g, "е"))) return area.chatTitle
    }
  }

  return FALLBACK_CHAT_TITLE
}

/** Все названия чатов, задействованные в правилах — для проверок. */
export function listRoutedChatTitles(): string[] {
  return [...AREAS.map((area) => area.chatTitle), FALLBACK_CHAT_TITLE]
}
