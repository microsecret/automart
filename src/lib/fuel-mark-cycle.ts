/**
 * Что происходит с маркой по нажатию.
 *
 * Отметить можно было только наличие: нажал 92 — «есть», нажал ещё раз —
 * снял. Отсутствие ставилось лишь скопом, кнопкой «нет вообще». А на
 * колонке обычная картина другая: 92-й есть, 95-го нет. Сказать про это
 * было нечем — «нет вообще» гасит все марки разом и врёт, а промолчать
 * про 95-й значит оставить следующего водителя в неведении ровно о том,
 * за чем он едет.
 *
 * Правило круга живёт здесь, а не в компоненте: от него зависит, что
 * увидят на карте тысячи людей, и оно должно проверяться тестами.
 */

/** Ответ по одной марке: «есть», «нет» или ещё не отвечали. */
export type FuelMark = "YES" | "NO" | null

/**
 * Следующее состояние по кругу: пусто → есть → нет → пусто.
 *
 * Наличие первым, потому что так отвечают чаще: человек подъехал,
 * заправился и отмечает, что взял. Отсутствие вторым — оно тоже ответ, и
 * стоит того же одного касания.
 */
export function nextFuelMark(current: FuelMark): FuelMark {
  if (current === null) return "YES"
  if (current === "YES") return "NO"
  return null
}

/**
 * Нужна ли цена при таком ответе.
 *
 * Цена того, чего нет, — бессмыслица: она осталась бы от прошлого
 * нажатия и ушла бы на сервер вместе с «нет».
 */
export function keepsPrice(mark: FuelMark): boolean {
  return mark === "YES"
}
