/**
 * Какое по счёту напоминание отправлять.
 *
 * Считается по времени от знакомства с ботом, а не отдельным полем: так
 * не нужна миграция схемы, а расхождение между счётчиком и реальностью
 * невозможно.
 *
 * Возвращает −1, когда писать не нужно: до двух недель человек ещё
 * помнит о боте сам, после четырёх напоминаний бот замолкает.
 */
export function nudgeIndex(startedAt: Date, now: Date): number {
  const elapsed = now.getTime() - startedAt.getTime()
  if (!Number.isFinite(elapsed) || elapsed < FIRST_NUDGE_DELAY_MS) return -1
  const index = Math.floor(elapsed / NUDGE_INTERVAL_MS) - 1
  return index >= 0 && index < MAX_NUDGES ? index : -1
}

/** Текст напоминания по номеру. Имя подставляется только в первое. */
export function nudgeText(index: number, firstName?: string | null): string {
  if (index < 0 || index >= NUDGE_VARIANTS.length) return ""
  const lines = [...NUDGE_VARIANTS[index]]
  const name = firstName?.trim()
  if (name && index === 0) {
    lines[0] = lines[0].replace("<b>", `<b>${escapeHtml(name)}, `)
  }
  return lines.join("\n")
}

function escapeHtml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
}
