/**
 * Цена топлива из копеек в рубли: «67,05» или «70».
 *
 * Дробная часть показывается, только когда она есть: «70,00 ₽» на
 * колонке не пишут, а лишние нули в столбце цен мешают сравнивать
 * глазами.
 *
 * Копейки здесь не мелочь. Разница в семьдесят копеек на литр — это
 * сорок рублей на бак, и ровно по ней человек выбирает между двумя
 * заправками на перекрёстке. Округление до рубля стирало то самое, ради
 * чего цену и смотрят.
 *
 * Отдельный модуль, а не строка в общем `format`: тот тянет за собой
 * разбор картинок и числовые форматы, а эту функцию должен уметь
 * позвать тест напрямую.
 */
export function formatFuelKopecks(kopecks: number): string {
  const roubles = kopecks / 100
  return new Intl.NumberFormat("ru-RU", {
    minimumFractionDigits: Number.isInteger(roubles) ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(roubles)
}
