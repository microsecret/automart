/**
 * Приведение заголовка объявления к человеческому виду.
 *
 * Заголовок пишет продавец, и пишет как придётся: «ваз 2105 в хорошем
 * состоянии», «Лада калина 1», «ПРОДАМ СРОЧНО». В выдаче такие строки
 * стоят рядом с аккуратными, и каталог выглядит неопрятно — а по опрятности
 * судят о площадке целиком.
 *
 * Правила намеренно осторожные. Заголовок — слова самого человека, и
 * переписывать его нельзя: правится только очевидное, что он и сам счёл бы
 * опечаткой.
 *
 * Модуль без импортов: то, что видят все посетители каталога, должно
 * проверяться тестами.
 */

/* Марки и слова, которые пишут заглавными не по ошибке.

   «ВАЗ», «КАМАЗ», «УАЗ», «BMW» — это сокращения, и приводить их к «Ваз»
   значит портить правильное написание. */
const KEEP_UPPERCASE = new Set([
  "ВАЗ", "ГАЗ", "УАЗ", "КАМАЗ", "ЗИЛ", "МАЗ", "КРАЗ", "ПАЗ", "ЛИАЗ",
  "BMW", "VW", "GMC", "KIA", "MG", "DS", "SUV", "ADR", "VIN", "ПТС", "СТС",
  "АКПП", "МКПП", "КПП", "ГБО", "ABS", "ESP", "EGR", "TDI", "GTI", "AWD",
])

/** Слово целиком заглавными и длиннее двух букв — крик, а не сокращение. */
function isShouting(word: string): boolean {
  const letters = word.replace(/[^A-Za-zА-Яа-яЁё]/g, "")
  if (letters.length < 3) return false
  if (KEEP_UPPERCASE.has(letters.toUpperCase())) return false
  return letters === letters.toUpperCase()
}

function capitalize(word: string): string {
  if (!word) return word
  return word.charAt(0).toLocaleUpperCase("ru-RU") + word.slice(1)
}

/**
 * Приводит заголовок к опрятному виду.
 *
 * Что делает:
 * • убирает лишние пробелы и повторы знаков препинания;
 * • гасит крик заглавными — «ПРОДАМ СРОЧНО» становится «Продам срочно»;
 * • поднимает первую букву;
 * • известные сокращения оставляет как есть.
 *
 * Чего не делает: не трогает середину предложения, не переставляет слова,
 * не дописывает марку. Это по-прежнему заголовок продавца.
 */
export function tidyListingTitle(raw: string): string {
  const collapsed = raw
    .replace(/\s+/g, " ")
    .replace(/!{2,}/g, "!")
    .replace(/\?{2,}/g, "?")
    .replace(/\.{4,}/g, "…")
    .trim()

  if (!collapsed) return ""

  /* Крик гасим целиком в строчные: заглавная останется только у первого
     слова, ниже. Поднимать каждое слово нельзя — «ПРОДАМ СРОЧНО ТОРГ»
     превратилось бы в «Продам Срочно Торг», что по-русски читается как
     ошибка, а не как исправление. */
  const words = collapsed.split(" ").map((word) => (
    isShouting(word) ? word.toLocaleLowerCase("ru-RU") : word
  ))

  const joined = words.join(" ")
  return capitalize(joined)
}

/**
 * Подставляет марку и модель из справочника, если продавец написал их иначе.
 *
 * «Лада калина 1» при справочных «Лада» и «Калина» — это опечатка в
 * регистре, а не выбор автора: то же слово в справочнике записано верно.
 * Заменяем только когда совпадение отличается лишь регистром — иначе
 * оставляем как есть, это может быть уточнение вроде «калина-универсал».
 */
export function alignTitleWithCatalog(title: string, make?: string | null, model?: string | null): string {
  /* Разбором по словам, а не выражением с подстановкой.

     Название марки приходит из справочника и попадало бы в регулярное
     выражение как есть: «Ростов-на-Дону» или «Mercedes-Benz» читались бы
     там как набор символов, а не как слово. Разбор по словам от этого
     свободен. */
  const references = [make, model]
    .map((value) => value?.trim())
    .filter((value): value is string => Boolean(value))

  if (references.length === 0) return title

  const byLowercase = new Map(references.map((value) => [value.toLocaleLowerCase("ru-RU"), value]))

  return title
    .split(" ")
    .map((word) => byLowercase.get(word.toLocaleLowerCase("ru-RU")) ?? word)
    .join(" ")
}
