/**
 * Что бот пишет продавцу, когда объявление вышло на площадку.
 *
 * Решение модератора и раньше записывалось в уведомления, но только на
 * сайт — в колокольчик. Из ста двадцати человек сто девятнадцать пришли
 * из Telegram и на сайт заходят редко: продавец отправлял машину на
 * проверку и не узнавал, что она опубликована, пока сам не заглянет.
 *
 * Здесь только текст и кнопки, без сети и базы: то, что уходит живому
 * человеку, должно проверяться тестами.
 */

/** Экранирование: заголовок пишет человек, а сообщение идёт с HTML. */
function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
}

export type PublishedMessage = {
  text: string
  buttons: { text: string; url: string }[]
}

export type PublishedInput = {
  listingId: string
  title: string
  /** Название чата, куда объявление ушло; null — не ушло никуда. */
  chatTitle: string | null
  siteUrl: string
  botUsername?: string
  /**
   * Объявление публиковалось раньше, а в чат уходит только сейчас.
   *
   * Досылает те объявления, что были одобрены до появления рассылки.
   * Говорить их продавцу «объявление опубликовано» нельзя: оно
   * опубликовано неделю назад, и такое сообщение читается как сбой.
   */
  alreadyPublished?: boolean
}

/**
 * Собирает сообщение о публикации.
 *
 * Про чат сказано отдельно и первым делом после самой новости: для
 * продавца это главная польза площадки — объявление увидели не только
 * зашедшие на сайт, но и подписчики группы его города. Без этой строки
 * бесплатная рассылка остаётся невидимой, и человек не понимает, за что
 * потом платить продвижение.
 */
export function buildPublishedMessage(input: PublishedInput): PublishedMessage {
  const name = input.title.trim() || "Объявление"
  const site = input.siteUrl.replace(/\/$/, "")
  const path = `/listings/vehicle/${input.listingId}`

  const lines = input.alreadyPublished
    /* Объявление давно на площадке — новость здесь только про чат, и
       заголовок обязан говорить именно о ней. */
    ? [`📣 <b>Объявление ушло в чат</b>`, "", `«${escapeHtml(name)}» показали подписчикам группы.`]
    : [`✅ <b>Объявление опубликовано</b>`, "", `«${escapeHtml(name)}» прошло проверку и видно покупателям.`]

  if (input.chatTitle) {
    lines.push("", input.alreadyPublished
      ? `Чат: «${escapeHtml(input.chatTitle)}».`
      : `📣 Отправили в чат «${escapeHtml(input.chatTitle)}» — его увидят подписчики группы.`)
  }

  /* Продвижение упомянуто одной строкой и без нажима: человек только что
     получил хорошую новость, и уместно сказать, что можно быстрее, — но
     превращать поздравление в объявление о продаже услуг нельзя. */
  lines.push("", "Продать быстрее поможет продвижение — в кабинете, раздел «Продвижение».")

  const buttons: { text: string; url: string }[] = []

  /* Открытие в приложении первым: человек читает это в Telegram, и
     приложение открывается прямо здесь, а ссылка на сайт выбрасывает его
     в браузер, где он заново входит в учётную запись. */
  if (input.botUsername) {
    buttons.push({
      text: "📱 Открыть в приложении",
      url: `https://t.me/${input.botUsername}?startapp=listing_${input.listingId}`,
    })
  }

  buttons.push({ text: "🔎 Посмотреть на сайте", url: `${site}${path}` })

  /* Кнопка «отправить друзьям».

     Продавец получает поздравление с публикацией — это ровно тот
     момент, когда он больше всего готов показать машину знакомым. Но
     кнопок было две, и обе для него самого: открыть в приложении и
     посмотреть на сайте. Чтобы отправить объявление в семейный чат
     или коллегам, надо было копировать ссылку руками, и почти никто
     этого не делал.

     Ссылка t.me/share открывает окно выбора чата прямо в Telegram:
     человек в два касания отправляет объявление куда угодно. Она
     переживает пересылку, в отличие от кнопок web_app, которые
     привязаны к чату с ботом и у получателя не работают.

     Ведёт на сайт, а не в мини-приложение: у получателя бота может не
     быть вовсе, а сайт откроется у любого. */
  const shareUrl = `${site}${path}`
  buttons.push({
    text: "📤 Отправить друзьям",
    url: `https://t.me/share/url?url=${encodeURIComponent(shareUrl)}&text=${encodeURIComponent(input.title)}`,
  })

  return { text: lines.join("\n"), buttons }
}
