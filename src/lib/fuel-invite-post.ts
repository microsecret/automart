/**
 * Приглашение в сервис «где есть бензин» — для чатов и пересылки.
 *
 * Карта наличия работает ровно настолько, насколько людей на ней. Десять
 * человек в городе дают карту, которой нельзя верить; тысяча — сервис,
 * который экономит каждому по часу в очереди. Поэтому приглашение здесь
 * не украшение, а условие работы.
 *
 * Текст написан так, чтобы его хотелось переслать. Это значит: без
 * рекламных оборотов, с понятной пользой в первой строке и с честным
 * признанием, что сервис держится на самих водителях.
 *
 * Модуль без импортов: то, что уходит тысячам посторонних людей, должно
 * проверяться тестами без базы и сети.
 */

/** Экранирование: название города приходит из справочника. */
function escapeHtml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
}

export type InvitePost = {
  text: string
  buttons: Array<{ text: string; url: string }>
}

export type InviteInput = {
  /** Город чата — приглашение говорит про него, а не про страну вообще. */
  city?: string | null
  siteUrl: string
  botUsername?: string
  /** Сколько отметок уже сделали в этом городе; 0 — сервис только начали. */
  reportsCount?: number
}

/**
 * Собирает приглашение для чата.
 *
 * Порядок продуман под чтение по диагонали: сначала боль, которую человек
 * узнаёт («стоял час, а там пусто»), потом решение одной строкой, потом
 * что от него требуется. Просьба рассказать — в конце, когда польза уже
 * понятна: просить раньше значит просить у того, кто ещё не понял за что.
 */
export function buildFuelInvitePost(input: InviteInput): InvitePost {
  const site = input.siteUrl.replace(/\/$/, "")
  const city = input.city?.trim()

  const lines: string[] = [
    "⛽ <b>Где сейчас есть бензин — карта от самих водителей</b>",
    "",
    "Приехал на заправку, а там пусто. Проехал полгорода — очередь на сорок минут.",
    "Знакомо?",
    "",
    city
      ? `Мы сделали карту АЗС ${escapeHtml(city)}: видно, где топливо есть прямо сейчас, а где закончилось.`
      : "Мы сделали карту АЗС: видно, где топливо есть прямо сейчас, а где закончилось.",
    "",
    "<b>Как это работает</b>",
    "Данные дают сами водители. Заправился — отметил за две секунды, и следующий",
    "не поедет туда впустую. Завтра кто-то отметит для тебя.",
  ]

  /* Число отметок называется, только когда их достаточно, чтобы
     впечатлить. «Уже 4 отметки» отпугивает сильнее, чем молчание: человек
     видит пустой сервис и не возвращается. */
  if (typeof input.reportsCount === "number" && input.reportsCount >= 50) {
    lines.push("", `📊 Уже ${input.reportsCount.toLocaleString("ru-RU")} отметок от водителей.`)
  }

  lines.push(
    "",
    "<b>Что умеет</b>",
    "• 🗺 Карта: зелёная точка — топливо есть, красная — закончилось",
    "• 📍 «Куда ехать» — ближайшая заправка с нужной маркой",
    "• 🔔 Уведомление, когда на вашей АЗС появится 92-й",
    "• 💬 Отметка прямо в боте: пришлите точку — бот спросит кнопками",
    "",
    "<b>Бесплатно и без регистрации</b> — смотреть карту может каждый.",
    "",
    /* Просьба рассказать — в конце и без нажима. «Поделитесь с друзьями»
       читается как реклама; «чем больше нас, тем точнее» объясняет, зачем
       это самому человеку. */
    "👥 Перешлите знакомым автомобилистам — чем больше нас, тем точнее карта",
    "и тем меньше все стоим в очередях впустую. Помогаем друг другу на дорогах.",
  )

  const buttons: Array<{ text: string; url: string }> = [
    { text: "🗺 Открыть карту", url: `${site}/services/fuel-map?from=telegram` },
  ]

  if (input.botUsername) {
    /* Бот второй кнопкой: карту можно смотреть без него, а отмечать из
       бота удобнее — но это следующий шаг, а не первый. */
    buttons.push({ text: "⛽ Отмечать через бота", url: `https://t.me/${input.botUsername}` })
  }

  /* Кнопка пересылки.

     Пост живёт в городском чате, где его читают сотни человек, и
     каждый второй знает кого-то, кому карта нужнее. Но переслать её
     можно было только руками — выделить, скопировать, найти чат.

     Ссылка t.me/share открывает выбор чата прямо в Telegram, а текст
     для пересылки в этом же файле уже написан: три строки, которые
     читаются как совет, а не как реклама. */
  buttons.push({
    text: "📤 Переслать другу",
    url: `https://t.me/share/url?url=${encodeURIComponent(`${site}/services/fuel-map`)}&text=${encodeURIComponent("Где сейчас есть бензин — карта отметок водителей")}`,
  })

  return { text: lines.join("\n"), buttons }
}

/**
 * Короткое приглашение — для пересылки одним человеком другому.
 *
 * Длинный пост в личной переписке читается как реклама, которую переслали
 * не глядя. Здесь три строки и ссылка: так пересылают то, что считают
 * полезным.
 */
export function buildFuelShareText(input: { siteUrl: string; city?: string | null }): string {
  const site = input.siteUrl.replace(/\/$/, "")
  const city = input.city?.trim()

  return [
    "⛽ Карта заправок: где сейчас есть бензин",
    "",
    city
      ? `Водители ${escapeHtml(city)} отмечают, где топливо есть, а где закончилось.`
      : "Водители отмечают, где топливо есть, а где закончилось.",
    "Не поедешь впустую и не встанешь в очередь на сорок минут.",
    "",
    `${site}/services/fuel-map`,
  ].join("\n")
}

/**
 * Достаёт город из названия чата.
 *
 * «Авторынок Казань» → «Казань», «АВТОРЫНОК УФА/Башкортостан» → «Уфа».
 * Общий чат страны города не имеет — там приглашение говорит про сервис
 * вообще, и это правильно: его читают из разных городов.
 *
 * Живёт здесь, а не рядом с рассылкой: там модуль тянет Prisma, и
 * проверить чистую функцию тестами было бы нельзя.
 */
export function cityFromChatTitle(title: string | null): string | null {
  if (!title) return null

  /* «Бензин» наравне с «Авторынком»: у площадки два семейства чатов —
     под объявления и под топливо, и город достаётся из названия любого.
     Без этого чаты «Бензин Уфа», «Бензин Казань» и остальные считались
     безымянными и пропускались рассылкой целиком. */
  const cleaned = title
    .replace(/авторынок|бензин/gi, "")
    .replace(/\/.*$/, "")
    .trim()

  if (!cleaned || /росси/i.test(cleaned)) return null

  /* Приводим к обычному написанию: в названиях чатов встречается
     «АВТОРЫНОК УФА», и «карта АЗС УФА» в посте выглядит криком. */
  return cleaned.charAt(0).toUpperCase() + cleaned.slice(1).toLowerCase()
}

/**
 * Топливный ли это чат.
 *
 * У площадки два семейства чатов: «Авторынок Казань» — про объявления о
 * машинах, «Бензин Казань» — про наличие топлива. Новость «появился
 * АИ-95» в чате объявлений неуместна, а в бензиновом это и есть повод, по
 * которому люди туда пришли.
 *
 * Различать пришлось после боевого прогона: сообщения о топливе ушли в
 * «Авторынок Сочи» и «Авторынок Оренбург» — города, где бензинового чата
 * нет, и подходящим по названию оказался автомобильный.
 */
export function isFuelChatTitle(title: string | null): boolean {
  if (!title) return false
  return /бензин|топлив|азс|заправ/i.test(title)
}
