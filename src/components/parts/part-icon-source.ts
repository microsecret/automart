export function partIconSource(kind: string, label?: string): string | undefined {
  const category = queryCells[kind]
  if (!category) return undefined
  const cell = label === undefined ? categoryCells[kind] ?? 1 : category[label]
  return typeof cell === "number" ? `/images/ui/part-icons-v1/${kind}-${cell}.webp` : undefined
}
