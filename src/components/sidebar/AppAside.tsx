"use client"

import { Box } from "@mantine/core"
import RatesWidget from "./RatesWidget"
import FuelWidget from "./FuelWidget"
import FreshLotsWidget from "./FreshLotsWidget"
import FreshListingsWidget from "./FreshListingsWidget"
import NewsWidget from "./NewsWidget"

/**
 * Правая колонка страницы.
 *
 * Дром и Авто.ру устроены в одну колонку: лента блоков сверху вниз, по
 * бокам поля. Оттого они и похожи друг на друга — это один шаблон доски
 * объявлений. Три колонки с живыми данными по краям — то, чего у них
 * нет, и заодно ответ на пустые поля по краям экрана.
 *
 * Порядок виджетов — по тому, как часто в них заглядывают:
 *
 * 1. Заправки. Машину покупают раз в несколько лет, заправляются
 *    еженедельно. Это единственная причина зайти на сайт между
 *    покупками, поэтому стоит первой.
 * 2. Свежие лоты. Самое богатое, что есть у площадки: 16 007 машин,
 *    367 новых за сутки.
 * 3. Курсы ЦБ. Инструмент к лотам выше: цены приходят в иенах и вонах,
 *    и человек сверяет их рублями, не уходя со страницы.
 * 4. Свежие объявления. Их десятки против тысяч лотов — без отдельной
 *    строки их бы просто не заметили.
 * 5. Новости. Читают последними, зато они показывают, что площадка
 *    живая: сорок публикаций за сутки.
 *
 * Каждый виджет сам решает, показываться ли: при нехватке данных он
 * возвращает null и исчезает целиком. Пустая рамка с подписью «нет
 * данных» хуже отсутствия блока — она сообщает, что сервис не работает.
 */
export default function AppAside() {
  return (
    <Box component="aside" className="app-aside" aria-label="Сводка площадки">
      <FuelWidget />
      <FreshLotsWidget />
      <RatesWidget />
      <FreshListingsWidget />
      <NewsWidget />
    </Box>
  )
}
