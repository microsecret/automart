async function main() {
  let created = 0
  let updated = 0

  for (const article of ARTICLES) {
    const existing = await prisma.supportKnowledgeArticle.findUnique({
      where: { slug: article.slug },
      select: { id: true },
    })

    await prisma.supportKnowledgeArticle.upsert({
      where: { slug: article.slug },
      create: { ...article, isPublished: true },
      update: {
        title: article.title,
        summary: article.summary,
        content: article.content,
        keywords: article.keywords,
        link: article.link,
        sortOrder: article.sortOrder,
        isPublished: true,
      },
    })

    if (existing) updated += 1
    else created += 1
  }

  const total = await prisma.supportKnowledgeArticle.count({ where: { isPublished: true } })
  console.log(`Статьи поддержки: создано ${created}, обновлено ${updated}, всего опубликовано ${total}`)
}

main()
  .catch((error) => {
    console.error("Не удалось наполнить базу знаний:", error instanceof Error ? error.message : error)
    process.exitCode = 1
  })
  .finally(() => prisma.$disconnect())
