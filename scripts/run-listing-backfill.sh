#!/usr/bin/env bash
set -euo pipefail

# Объявления, не попавшие в чаты, уходят по одному за запуск.
#
# Свежее объявление уходит в чат само, при одобрении модератором. Сюда
# попадают те, что были опубликованы до появления рассылки, и те, чья
# отправка не прошла из-за сбоя сети.
#
# По одному за раз: десять постов подряд в чат читаются как захват
# группы, даже когда каждое объявление по делу. Решает приложение, здесь
# только регулярный вызов.
cd "$(dirname "$0")/.."
set -a
# Продакшн-.env живёт на сервере и не коммитится.
source ./.env
set +a

BASE_URL="${NEXTAUTH_URL:-http://127.0.0.1:3000}"

# Приложение может перезапускаться из-за деплоя ровно в момент запуска —
# короткий повтор не даёт потерять волну.
curl --fail --silent --show-error --connect-timeout 10 --max-time 120 \
  --retry 3 --retry-all-errors --retry-delay 3 \
  -X POST \
  -H "x-telegram-bot-api-secret-token: ${TELEGRAM_WEBHOOK_SECRET}" \
  "${BASE_URL}/api/telegram/listing-backfill"
echo
